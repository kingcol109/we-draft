// scripts/buildPortalSimTeams.mjs
//
// The Transfer Portal Sim's team list for its SEO tags — { [slug]: school }
// for every FBS school the sim plays as (/portalsim/florida-state), written
// to src/utils/portalSim/simTeams.js. The page's Helmet tags
// (components/portalSim/PortalSimMeta.jsx) and the static preview copies
// (scripts/buildPortalSimPreviewPages.mjs) read it, so team titles are there
// before any data loads. Read-only: the pool's teams doc (portalSimPool/teams).
// Re-run when the pool's FBS schools change, and commit the JSON.
// Usage:
//   node --env-file=.env scripts/buildPortalSimTeams.mjs
import { createRequire } from "module";
import { writeFileSync } from "fs";

const require = createRequire(import.meta.url);
const { getFirestore } = require("./firebaseAdmin");

const snap = await getFirestore().collection("portalSimPool").doc("teams").get();
const doc = snap.data();
if (!doc || !Array.isArray(doc.teams)) throw new Error("portalSimPool/teams has no teams");
// Rows (JSON strings): [slug, school, conference, lat, lng, fcs, brand].
const out = {};
doc.teams.map((s) => JSON.parse(s)).filter((t) => !t[5]).sort((a, b) => String(a[1]).localeCompare(String(b[1]))).forEach((t) => { out[t[0]] = t[1]; });
writeFileSync("src/utils/portalSim/simTeams.js", [
  "// Generated by scripts/buildPortalSimTeams.mjs: every FBS school the Transfer",
  "// Portal Sim plays as, { [slug]: school }. Don't edit by hand; re-run it.",
  `const SIM_TEAMS = ${JSON.stringify(out, null, 1)};`,
  "export default SIM_TEAMS;",
  "",
].join("\n"));
console.log(`Portal Sim teams: wrote ${Object.keys(out).length} FBS schools`);
